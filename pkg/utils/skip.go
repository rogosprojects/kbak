package utils

import (
	batchv1 "k8s.io/api/batch/v1"
	v1 "k8s.io/api/core/v1"
	rbacv1 "k8s.io/api/rbac/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// SkipReason returns why obj should be left out of a backup, or "" to back it up.
// These objects are recreated by the cluster; restoring them adds orphaned duplicates.
func SkipReason(obj interface{}) string {
	switch o := obj.(type) {
	case *v1.Pod, *batchv1.Job:
		// Pods of Deployments/StatefulSets/DaemonSets/Jobs, static mirror pods, and Jobs of CronJobs
		if ref := metav1.GetControllerOf(o.(metav1.Object)); ref != nil {
			return "managed by " + ref.Kind + "/" + ref.Name
		}
	case *v1.ConfigMap:
		switch o.Name {
		case "kube-root-ca.crt":
			return "published by Kubernetes in every namespace"
		case "openshift-service-ca.crt":
			return "published by OpenShift in every namespace"
		}
	case *v1.Secret:
		a := o.Annotations
		switch {
		// Image pull secrets (4.16+, and legacy dockercfg) and legacy SA tokens; regenerated for every ServiceAccount
		case a["openshift.io/internal-registry-auth-token.service-account"] != "",
			a["openshift.io/token-secret.name"] != "",
			a["kubernetes.io/created-by"] == "openshift.io/create-dockercfg-secrets":
			return "generated by OpenShift for its ServiceAccount"
		// Re-minted while the Service keeps service.beta.openshift.io/serving-cert-secret-name
		case a["service.beta.openshift.io/originating-service-name"] != "",
			a["service.alpha.openshift.io/originating-service-name"] != "":
			return "serving certificate generated by OpenShift for its Service"
		}
	case *rbacv1.RoleBinding:
		switch o.Name {
		case "system:image-pullers", "system:image-builders", "system:deployers":
			// Their subjects embed the source namespace, so a restore elsewhere would grant the wrong group
			return "managed by OpenShift in every namespace"
		}
	}
	return ""
}
